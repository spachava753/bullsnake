func inRuneRanges(r rune, ranges []runeRange) bool {
	low := 0
	high := len(ranges)
	for low < high {
		middle := low + (high-low)/2
		candidate := ranges[middle]
		switch {
		case r < candidate.first:
			high = middle
		case r > candidate.last:
			low = middle + 1
		default:
			return true
		}
	}
	return false
}
