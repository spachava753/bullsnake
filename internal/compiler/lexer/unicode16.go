package lexer

// These ranges are the Unicode 17 XID additions absent from Unicode 16.
// Bullsnake excludes them because CPython 3.14 uses UCD 16.0.0, while Go 1.27
// and golang.org/x/text use UCD 17.0.0. The ranges come from the XID_Start and
// XID_Continue properties in DerivedCoreProperties.txt for those releases.
type runeRange struct {
	first rune
	last  rune
}

